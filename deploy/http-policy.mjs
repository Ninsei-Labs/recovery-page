// THE PAGE'S HTTP POLICY, IN ONE PLACE.
//
// The two Bun servers, the generated Cloudflare `_headers` file, and the nginx example all describe the same
// page. Keeping the CSP and cache rules here means a change reaches the runtime servers without a second edit;
// the nginx block is checked against these values by the repository's tests because nginx cannot import this module.
//
// NO COEP. monero-ts 0.11 no longer needs SharedArrayBuffer, so the page is not cross-origin isolated. COOP stays:
// another site must not hold a handle to a tab that holds spend keys.

export const CSP = [
  "default-src 'self'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "worker-src 'self' blob:",
  "style-src 'self'",
  "img-src 'self' data:",
  // The node is the visitor's choice: any http(s) host must be reachable, or the field on the page would be a lie.
  "connect-src 'self' http: https:",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join("; ");

export const SECURITY_HEADERS = Object.freeze({
  "Cross-Origin-Opener-Policy": "same-origin",
  "Cross-Origin-Resource-Policy": "same-origin",
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "no-referrer",
});

export const IMMUTABLE_CACHE = "public, max-age=31536000, immutable";
export const WORKER_CACHE = "public, max-age=3600";
export const NO_CACHE = "no-cache";

// A FILE UNDER /assets/ carries a content hash in its `?v=` URL, so a year is safe. The worker is not stamped by
// the page's build in the same way and keeps an hour. Everything else is revalidated.
export function cacheControl(pathname) {
  if (String(pathname).startsWith("/assets/")) return IMMUTABLE_CACHE;
  if (pathname === "/monero.worker.js") return WORKER_CACHE;
  return NO_CACHE;
}

// Cloudflare Pages reads this file from the published directory. It is generated by the build, not edited by hand.
export function cloudflareHeaders() {
  return [
    "/*",
    `  Cross-Origin-Opener-Policy: ${SECURITY_HEADERS["Cross-Origin-Opener-Policy"]}`,
    `  Cross-Origin-Resource-Policy: ${SECURITY_HEADERS["Cross-Origin-Resource-Policy"]}`,
    `  X-Content-Type-Options: ${SECURITY_HEADERS["X-Content-Type-Options"]}`,
    `  Referrer-Policy: ${SECURITY_HEADERS["Referrer-Policy"]}`,
    `  Content-Security-Policy: ${CSP}`,
    "",
    "/assets/*",
    `  Cache-Control: ${IMMUTABLE_CACHE}`,
    "",
    "/monero.worker.js",
    `  Cache-Control: ${WORKER_CACHE}`,
    "",
    "/*.html",
    `  Cache-Control: ${NO_CACHE}`,
    "",
    "/build.json",
    `  Cache-Control: ${NO_CACHE}`,
    "",
  ].join("\n");
}
